// 获取翻译文本的辅助函数
export function getTranslation(key, lang = 'zh') {
  const keys = key.split('.')
  let result = translations[lang]
  
  for (const k of keys) {
    if (result && typeof result === 'object' && k in result) {
      result = result[k]
    } else {
      return key // 如果找不到翻译，返回原始key
    }
  }
  
  return result
}
